/**
 * `npm run duel:art` — the Ragdoll Rumble sprites, from the asset pack to the
 * cabinet.
 *
 * The pack lives in `assets/duel/` (README there; its `tools/` regenerate
 * every sheet from `source_svg/`). This script takes the subset the cabinet
 * actually draws and does two things with it:
 *
 *  1. Copies the sheets into `src/arcade/games/duel/art/`, where the cabinet
 *     imports them statically. That is deliberate, not tidiness: a static
 *     import is emitted under `/_next/static/media/` with a content hash, and
 *     `/_next/static/` is the one prefix the service worker already caches —
 *     so the art works offline exactly as the cabinet's code does. Served
 *     from `public/duel/` it would need a new entry in the worker's allowlist
 *     and would go stale behind a cache that never revalidates.
 *  2. Flattens the pack's Phaser JSON-hash atlases into `art/frames.ts`: four
 *     numbers per frame, no JSON fetched at run time.
 *
 * Only the @2x sheets are shipped. The view is letterboxed at up to about
 * 2.4 device pixels per view pixel on a phone, and a 32 px tile drawn from a
 * 64 px source is the difference between an outline and a smear.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const PACK = "assets/duel/textures";
const OUT = "src/arcade/games/duel/art";

interface PhaserFrame {
  frame: { x: number; y: number; w: number; h: number };
}

const SHEETS = [
  { id: "robot", json: `${PACK}/atlases/robot@2x.json`, image: `${PACK}/atlases/robot@2x.webp`, scale: 2 },
  { id: "items", json: `${PACK}/atlases/items@2x.json`, image: `${PACK}/atlases/items@2x.webp`, scale: 2 },
  { id: "vfx", json: `${PACK}/atlases/vfx@2x.json`, image: `${PACK}/atlases/vfx@2x.webp`, scale: 2 },
  { id: "ui", json: `${PACK}/atlases/ui@2x.json`, image: `${PACK}/atlases/ui@2x.webp`, scale: 2 },
  { id: "tiles", json: `${PACK}/arenas/magma_gauntlet/tiles.json`, image: `${PACK}/arenas/magma_gauntlet/tiles.webp`, scale: 1 },
] as const;

const COPIES: readonly [string, string][] = [
  ...SHEETS.map((s) => [s.image, `${s.id}.webp`] as [string, string]),
  [`${PACK}/arenas/magma_gauntlet/bg_far@2x.webp`, "bg_far.webp"],
  [`${PACK}/arenas/magma_gauntlet/bg_mid@2x.webp`, "bg_mid.webp"],
];

mkdirSync(OUT, { recursive: true });
for (const [from, to] of COPIES) copyFileSync(from, join(OUT, to));

const lines: string[] = [
  "// Generated by `npm run duel:art` from assets/duel/. Do not edit by hand.",
  "//",
  "// [x, y, w, h] in the sheet's own pixels, and the scale the sheet was drawn",
  "// at relative to the pack's @1x units (the @2x sheets are 2).",
  "",
  "export type Frame = readonly [number, number, number, number];",
  "",
];
for (const s of SHEETS) {
  const data = JSON.parse(readFileSync(s.json, "utf8")) as { frames: Record<string, PhaserFrame> };
  lines.push(`export const ${s.id.toUpperCase()}_SCALE = ${s.scale};`);
  lines.push(`export const ${s.id.toUpperCase()} = {`);
  for (const [name, f] of Object.entries(data.frames)) {
    const { x, y, w, h } = f.frame;
    lines.push(`  ${JSON.stringify(name)}: [${x}, ${y}, ${w}, ${h}],`);
  }
  lines.push("} as const satisfies Record<string, Frame>;");
  lines.push("");
}
writeFileSync(join(OUT, "frames.ts"), lines.join("\n"));
console.log(`duel art: ${COPIES.length} images and ${SHEETS.length} frame tables written to ${OUT}`);
