/**
 * Download the raw CC0 surface maps every block texture is built from.
 *
 *   node --import tsx scripts/fetch-textures.ts [--force]
 *
 * Reads TEXTURES in src/lib/texture-list.ts, asks Poly Haven's public API for
 * each slot's 1K JPG maps, and writes them to assets/raw-textures/<slot>/ as
 * albedo / normal / roughness / ao. Existing files are kept unless --force.
 *
 * ── Why Poly Haven, and only Poly Haven ──────────────────────────────────
 *
 * The texture spec lists ambientCG first, and it is a fine library, but its
 * download endpoint answers a script with a 302 to an HTML page. Poly Haven
 * publishes a JSON API with a direct URL per map per resolution, every asset
 * is CC0 1.0, and it carries the author list — so the provenance file this
 * script also writes is complete, not approximate. One source, one code path.
 *
 * ── Which maps ───────────────────────────────────────────────────────────
 *
 * `Diffuse`, `nor_gl`, `Rough`, `AO`. The GL normal, never the DirectX one —
 * DX flips the green channel and every bump lights inside-out. Displacement
 * is skipped: nothing here tessellates.
 *
 * The output of this script is gitignored. The strip that ships is produced
 * from it by scripts/build-textures.ts and IS committed, so a deploy never
 * needs the network or this script. Re-run it when a slot's source changes.
 */
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { TEXTURES } from "@/lib/texture-list";

const API = "https://api.polyhaven.com";
const RAW_DIR = join(process.cwd(), "assets", "raw-textures");
const CREDITS = join(process.cwd(), "public", "textures", "CREDITS.md");
const RES = "1k";
const force = process.argv.includes("--force");

/** Poly Haven map name → the file the build script expects. */
const MAPS: Array<[apiName: string, file: string, required: boolean]> = [
  ["Diffuse", "albedo.jpg", true],
  ["nor_gl", "normal.jpg", true],
  ["Rough", "roughness.jpg", true],
  ["AO", "ao.jpg", false],
];

interface FileEntry {
  url: string;
  size: number;
}
type FilesResponse = Record<string, Record<string, Record<string, FileEntry>>>;
interface InfoResponse {
  name: string;
  authors?: Record<string, string>;
}

async function getJson<T>(url: string): Promise<T> {
  const res = await fetch(url, { headers: { "user-agent": "blockworld-textures" } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return (await res.json()) as T;
}

async function download(url: string, to: string) {
  const res = await fetch(url, { headers: { "user-agent": "blockworld-textures" } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  writeFileSync(to, Buffer.from(await res.arrayBuffer()));
}

interface Credit {
  slot: string;
  id: string;
  name: string;
  authors: string;
}

async function main() {
  mkdirSync(RAW_DIR, { recursive: true });
  const credits: Credit[] = [];

  for (const slot of TEXTURES) {
    if (!slot.source) continue;
    const dir = join(RAW_DIR, slot.name);
    mkdirSync(dir, { recursive: true });

    const [files, info] = await Promise.all([
      getJson<FilesResponse>(`${API}/files/${slot.source}`),
      getJson<InfoResponse>(`${API}/info/${slot.source}`),
    ]);

    for (const [apiName, file, required] of MAPS) {
      const entry = files[apiName]?.[RES]?.jpg;
      const to = join(dir, file);
      if (!entry) {
        if (required) throw new Error(`${slot.source} has no ${apiName} at ${RES}`);
        console.log(`  ${slot.name}: no ${apiName} map — the build will treat it as flat`);
        continue;
      }
      if (existsSync(to) && !force) {
        console.log(`  ${slot.name}/${file}: kept`);
        continue;
      }
      await download(entry.url, to);
      console.log(`  ${slot.name}/${file}: ${(entry.size / 1024).toFixed(0)} KB`);
    }

    credits.push({
      slot: slot.name,
      id: slot.source,
      name: info.name,
      authors: Object.keys(info.authors ?? {}).join(", ") || "Poly Haven",
    });
  }

  // The provenance file. Ten minutes of work that ends any licence question
  // on a monetised site instantly, per the spec's Part 1.
  const rows = credits
    .map(
      (c) =>
        `| ${c.slot} | [${c.name}](https://polyhaven.com/a/${c.id}) | ${c.authors} | CC0 1.0 |`
    )
    .join("\n");
  mkdirSync(join(CREDITS, ".."), { recursive: true });
  writeFileSync(
    CREDITS,
    `# Texture provenance

Every block surface is built from a CC0 1.0 source, or generated in this repo.
CC0 requires no attribution; the authors are listed anyway. Regenerated by
\`npm run textures:fetch\` — edit \`src/lib/texture-list.ts\`, not this file.

| Slot | Source | Authors | Licence |
|---|---|---|---|
| plain | generated (flat identity layer, \`scripts/build-textures.ts\`) | — | Self-generated |
${rows}
| detail | generated (tileable value noise, \`scripts/build-textures.ts\`) | — | Self-generated |
`
  );
  console.log(`Wrote ${CREDITS}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
