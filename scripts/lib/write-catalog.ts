import { writeFileSync } from "node:fs";
import { join } from "node:path";

export interface CatalogEntry {
  id: string;
  name: string;
  /** Metres, after gltf-pipeline's base-center/normalize pass. */
  size: [number, number, number];
}

const CATALOG_PATH = join(process.cwd(), "src", "lib", "props-catalog.ts");

/**
 * Regenerates `src/lib/props-catalog.ts` — a plain data module, like
 * `built-in-worlds.ts`, so the prop browser and the Play-mode collider both
 * import one typed, tree-shakeable array instead of fetching JSON at runtime.
 *
 * `baseUrl` is where the GLBs and thumbnails actually live: `/props` for the
 * public/ dev copies, or the R2 public URL once scripts/upload-props.ts has
 * pushed them there. Re-run whichever script matches how you're serving
 * assets and this file is overwritten to match — it's generated, not
 * hand-edited.
 */
export function writeCatalog(entries: CatalogEntry[], baseUrl: string) {
  const trimmedBase = baseUrl.replace(/\/$/, "");
  const body = entries
    .map(
      (e) => `  {
    id: ${JSON.stringify(e.id)},
    name: ${JSON.stringify(e.name)},
    url: ${JSON.stringify(`${trimmedBase}/${e.id}.glb`)},
    thumbnailUrl: ${JSON.stringify(`${trimmedBase}/thumbs/${e.id}.jpg`)},
    size: [${e.size.map((n) => n.toFixed(4)).join(", ")}],
  },`
    )
    .join("\n");

  writeFileSync(
    CATALOG_PATH,
    `// AUTO-GENERATED by scripts/optimize-props.ts / scripts/upload-props.ts — do not hand-edit.
// Source prompts: scripts/prop-catalog-source.ts. Regenerate with:
//   node --import tsx scripts/meshy-batch.ts && node --import tsx scripts/optimize-props.ts
import type { Vec3 } from "./worlddoc";

export interface PropCatalogEntry {
  id: string;
  name: string;
  url: string;
  thumbnailUrl: string;
  /** Metres — the prop's footprint before any per-instance scale is applied. */
  size: Vec3;
}

export const PROP_CATALOG: PropCatalogEntry[] = [
${body}
];

export const PROP_BY_ID: ReadonlyMap<string, PropCatalogEntry> = new Map(
  PROP_CATALOG.map((p) => [p.id, p])
);
`
  );
}
