/**
 * A guide page per playable thing: what it is, how it is built, how to play it.
 *
 * ── Why these pages exist at all ─────────────────────────────────────────
 *
 * Because `/play/<slug>` cannot be read. It is a canvas, and a crawler that
 * fetches it receives a document with no words in it — twenty-seven of those,
 * one per shipped world, is what "auto-generated pages with no unique
 * content" means in the abstract and what it looked like on this domain in
 * particular. The app surface and the readable surface had collapsed into one
 * URL, and the readable half was missing.
 *
 * So they are split. `/play/<slug>` is the game and is `noindex` — see its
 * own file. This is the page about the game, and it is the one in the
 * sitemap.
 *
 * ── Why it is not a template with the name swapped ───────────────────────
 *
 * That is the other half of the same rejection, and avoiding it is not a
 * matter of writing more words. Every number on this page comes from
 * `content/course-facts.ts`, which is generated by solving the course and
 * measuring the geometry the game actually builds — so Spindle's page says
 * 24 jumps in an 18x16 footprint and Overclock's says 30 jumps in a corridor
 * 119 long, because that is what they are. The prose in `course-notes.ts` is
 * written against those numbers.
 *
 * A page that can only be written about one course is the opposite of a
 * template, and it is the only defence against that flag that actually holds.
 *
 * ── Static, and completely ───────────────────────────────────────────────
 *
 * `generateStaticParams` covers every slug, nothing here touches the
 * database, and the facts are constants. These pages are HTML on disk, which
 * is what both a crawler and a slow phone want from them.
 */

/** Course, sandbox world and cabinet alike — every guide this route serves. */
const GUIDABLE = new Set(["course", "world", "arcade"]);

const guidable = (e: GameEntry) => GUIDABLE.has(e.kind);

export function generateStaticParams() {
  return REGISTRY.filter(guidable).map((e) => ({ slug: e.slug }));
}

/** The tier a course sits in, or undefined for anything that is not one. */
const tierOf = (slug: string) =>
  PARKOUR_COURSES.find((c) => c.slug === slug)?.tier;

/** Where the thing itself is played, as opposed to read about. */
function playHref(entry: GameEntry): string {
  return entry.kind === "arcade"
    ? `/arcade?play=${entry.slug}`
    : `/play/${entry.slug}`;
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ slug: string }>;
}): Promise<Metadata> {
  const { slug } = await params;
  const entry = bySlug.get(slug);
  if (!entry || !guidable(entry)) return {};

  const tier = tierOf(slug);
  // The description is built from what this thing actually is rather than
  // from one string repeated with a name substituted: the tier and the
  // measured shape are different for every course, so the search result is
  // too.
  const facts = factsFor(slug);
  const shape = facts?.route
    ? `${facts.route.jumps} jumps, ${facts.checkpoints} checkpoints, ${facts.route.climb} cells of climb.`
    : facts
      ? `${facts.parts.toLocaleString()} blocks.`
      : "";
  const kindWord =
    entry.kind === "arcade"
      ? "Arcade cabinet"
      : tier
        ? `${tier} parkour course`
        : "Sandbox world";

  return {
    title: `${entry.title} — ${kindWord} · ${SITE_NAME}`,
    description: `${entry.tagline} ${shape} How it is built and how to play it.`.trim(),
    alternates: { canonical: `${SITE_URL}/games/${slug}` },
    openGraph: {
      title: `${entry.title} · ${SITE_NAME}`,
      description: entry.tagline,
      url: `${SITE_URL}/games/${slug}`,
      type: "article",
      images: entry.thumb ? [{ url: entry.thumb }] : undefined,
    },
  };
}

/** A prose block. The guides are read, so the measure is capped in CSS. */
function Section({
  title,
  children,
}: {
  title: string;
  children: React.ReactNode;
}) {
  return (
    <section className="flex flex-col gap-2">
      <h2 className="text-ink text-lg font-bold">{title}</h2>
      <div className="text-dim flex flex-col gap-3 text-sm leading-relaxed">
        {children}
      </div>
    </section>
  );
}

export default async function GuidePage({
  params,
}: {
  params: Promise<{ slug: string }>;
}) {
  const { slug } = await params;
  const entry = bySlug.get(slug);
  if (!entry || !guidable(entry)) notFound();

  const tier = tierOf(slug);
  const facts = factsFor(slug);
  const notes = notesFor(slug);
  const cabinet = entry.kind === "arcade" ? cabinetNotesFor(slug) : undefined;
  const medals = entry.kind === "course" ? medalTimes(slug) : null;
  const href = playHref(entry);

  // Everything else in the same tier, for somebody who has just finished this
  // one. A "related" rail that lists the whole ladder is navigation; one that
  // lists the four courses at the same difficulty is a recommendation.
  const siblings = tier
    ? PARKOUR_COURSES.filter((c) => c.tier === tier && c.slug !== slug)
    : REGISTRY.filter(
        (e) => e.kind === entry.kind && e.slug !== slug
      ).slice(0, 4);

  const kindWord =
    entry.kind === "arcade"
      ? "Arcade cabinet"
      : tier
        ? `${tier} course`
        : "Sandbox world";

  /** Where this thing lives. Used by the breadcrumb and the secondary button. */
  const parent =
    entry.kind === "arcade"
      ? { href: "/arcade", label: "Arcade" }
      : entry.kind === "world"
        ? { href: "/games", label: "Games" }
        : { href: "/parkour", label: "Parkour" };

  return (
    <PageShell mode={entry.kind === "course" ? "parkour" : undefined}>
      {/* The parent is the page this thing actually lives on: the arcade for
          a cabinet, the ladder for a course, and `/games` for a sandbox world
          — which is on neither of the other two and would be claiming a
          progression it is deliberately outside of. */}
      <Breadcrumbs
        trail={[
          { href: "/", label: SITE_NAME },
          parent,
          { href: `/games/${slug}`, label: entry.title },
        ]}
      />

      <PageHeader title={entry.title} back={null}>
        <p className="hud-label">{kindWord}</p>
        <p className="text-dim max-w-xl text-sm">{entry.tagline}</p>
        <div className="mt-4 flex flex-wrap gap-2">
          <Link href={href} className="hud-chip hud-chip--primary px-6 py-3">
            {entry.kind === "arcade"
              ? "Play this cabinet"
              : entry.kind === "world"
                ? "Open this world"
                : "Play this course"}
          </Link>
          <Link href={parent.href} className="hud-chip px-6 py-3">
            {entry.kind === "arcade"
              ? "All cabinets"
              : entry.kind === "world"
                ? "All games"
                : "The whole ladder"}
          </Link>
        </div>
      </PageHeader>

      <div className="flex max-w-2xl flex-col gap-8">
        {notes && (
          <>
            <Section title="What it is">
              <p>{notes.what}</p>
            </Section>
            <Section title={facts?.route ? "The route" : "What is in it"}>
              <p>{notes.route}</p>
            </Section>
            {notes.approach && (
              <Section title="How to approach it">
                <p>{notes.approach}</p>
                {notes.teaches && (
                  <p>
                    <span className="text-ink font-semibold">
                      What it teaches:
                    </span>{" "}
                    {notes.teaches}
                  </p>
                )}
              </Section>
            )}
          </>
        )}

        {cabinet && (
          <>
            <Section title="What it is">
              <p>{cabinet.what}</p>
            </Section>
            <Section title="How it scores">
              <p>{cabinet.scoring}</p>
              {rateFor(slug) > 0 && (
                <p>
                  The cabinet pays{" "}
                  <span className="num text-ink">{rateFor(slug)}</span> coins
                  per point of score, before the daily cap described on the{" "}
                  <Link href="/arcade" className="text-accent underline">
                    arcade page
                  </Link>
                  .
                </p>
              )}
            </Section>
            <Section title="How to approach it">
              <p>{cabinet.approach}</p>
            </Section>
          </>
        )}

        {/* A cabinet has no route, no ladder rank and no medal times, so it
            gets the facts it does have — the rate, what that implies about
            farming it, the tempo — rather than a shorter page. */}
        {cabinet && <CabinetFacts slug={slug} />}

        {facts && <Facts slug={slug} facts={facts} />}

        {/* Only renders where this course actually holds a record — see the
            component. It is the section that cannot be written about any
            other page, which is the point of it. */}
        <Standouts slug={slug} />

        {medals && medals.length > 0 && (
          <Section title="Medal times">
            <p>
              Derived from this course&apos;s own geometry, not typed in —{" "}
              <Link
                href="/how-courses-are-made"
                className="text-accent underline"
              >
                how the times are worked out
              </Link>
              .
            </p>
            <table className="mt-1 w-full max-w-sm text-left text-sm">
              <thead>
                <tr className="text-dim border-b border-[var(--border-color)]">
                  <th className="py-2 font-medium">Medal</th>
                  <th className="py-2 font-medium">Time</th>
                </tr>
              </thead>
              <tbody>
                {medals.map(({ medal, ms }) => (
                  <tr
                    key={medal}
                    className="border-b border-[var(--border-color)]/50"
                  >
                    <td className="text-ink py-2">{MEDAL_LABELS[medal]}</td>
                    <td className="num py-2">{formatTime(ms)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </Section>
        )}

        <Controls kind={entry.kind === "arcade" ? "arcade" : "foot"} slug={slug} />

        {siblings.length > 0 && (
          <Section
            title={tier ? `Other ${tier} courses` : "More like this"}
          >
            <ul className="flex flex-col gap-2">
              {siblings.map((s) => (
                <li key={s.slug}>
                  <Link
                    href={`/games/${s.slug}`}
                    className="text-accent underline"
                  >
                    {"name" in s ? s.name : s.title}
                  </Link>
                  {" — "}
                  {"blurb" in s ? s.blurb : (s as GameEntry).tagline}
                </li>
              ))}
            </ul>
          </Section>
        )}

        {/* Under the content, never over it — see lib/ads. */}
        <AdSlot placement="guide" />
      </div>

      {/* Structured data, so the thing a search result describes is the game
          rather than a page that happens to mention one. */}
      <JsonLd
        data={{
          "@context": "https://schema.org",
          "@type": "VideoGame",
          name: entry.title,
          description: notes?.what ?? cabinet?.what ?? entry.tagline,
          url: `${SITE_URL}/games/${slug}`,
          playMode: "SinglePlayer",
          applicationCategory: "Game",
          gamePlatform: "Web browser",
          operatingSystem: "Any",
          genre:
            entry.kind === "arcade" ? "Arcade" : tier ? "Platformer" : "Sandbox",
          publisher: { "@type": "Organization", name: SITE_NAME, url: SITE_URL },
          offers: {
            "@type": "Offer",
            price: "0",
            priceCurrency: "USD",
            availability: "https://schema.org/InStock",
          },
        }}
      />
    </PageShell>
  );
}
