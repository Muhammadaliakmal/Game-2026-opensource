/**
 * The rooms, by hand.
 *
 * 24 columns by 12 rows. `#` wall, `.` air, `P` start, `G` goal, `^` spike,
 * `o` coin, `X` glass (breaks after a long enough fall), `~` light gravity.
 *
 * `par` is the fewest flips the solver in `solver.ts` needs. The test file
 * runs the solver over every room, so a room that cannot be done fails the
 * suite rather than the player, and a `par` that drifts from the truth
 * fails it too.
 *
 * ── The ladder ───────────────────────────────────────────────────────────
 *
 * 1–2  Down is a choice. Reach the goal by tipping the room.
 * 3–4  Spikes. Some ways down are the wrong way, and the first obvious one
 *      usually is.
 * 5–6  Glass. It only breaks after a long enough fall, so the room has to
 *      be arranged to give the ball one.
 * 7–8  Mid-fall. The pocket with the goal in it has no floor under its
 *      mouth, so the only way in is to change down while still moving. The
 *      first has a light zone in the shaft to slow the fall; the second
 *      does not.
 */

export interface GravityLevel {
  name: string;
  hint: string;
  rows: string[];
  par: number;
}

