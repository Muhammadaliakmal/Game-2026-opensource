/**
 * What each shipped world is actually like to play.
 *
 * ── Why this file is separate from the registry ──────────────────────────
 *
 * The registry holds a `tagline`: one line, written to fit on a card. This
 * holds the several paragraphs a guide page needs, and the two have different
 * jobs — a tagline that grew into a paragraph would break every card on the
 * site, and a guide page built out of taglines would be four sentences long.
 *
 * ── The rule these were written under ────────────────────────────────────
 *
 * Every specific in here is either a fact from `course-facts.ts` — which is
 * generated by measuring the geometry — or a property of the course design
 * that can be checked by opening the course and looking at it. There are no
 * player counts, no average completion times, and no claims about how a
 * course "feels to most players", because there is no way to check those and
 * a number nobody can check is worth less than a sentence they can.
 *
 * ── What `approach` is for ───────────────────────────────────────────────
 *
 * One concrete thing to do differently, not encouragement. "Take the corner
 * on the pad, not in the air" is a tip; "stay focused and you'll get it" is
 * filler, and filler is the substance of every thin page ever flagged.
 */

export interface WorldNotes {
  /**
   * What this is, and what it is made of. Two or three sentences — the answer
   * to "what am I looking at" for somebody who arrived from a search result
   * and has not pressed play yet.
   */
  readonly what: string;
  /** How the route unfolds, in the order you meet it. */
  readonly route: string;
  /** One concrete thing to do differently. Absent for a world with no goal. */
  readonly approach?: string;
  /** What this course is teaching, in a few words. Courses only. */
  readonly teaches?: string;
}

